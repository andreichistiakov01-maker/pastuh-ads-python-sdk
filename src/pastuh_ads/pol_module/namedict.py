def _fold(s):
    """
    Сворачиваем две пары букв, которые в данных пишут как попало.

    ё → е — вынужденно: вход до словаря доходит уже без ё, NFKD раскладывает
    её на «е» + диакритику, а диакритика снимается. Ключи словаря обязаны
    быть в той же форме, иначе «артём» не найдётся никогда.

    й → и — по данным: среднеазиатские имена в базе встречаются в обоих
    написаниях, «Айгерим» и «Аигерим», «Нурай» и «Нураи». Свёртка убирает
    целый класс промахов и ничего не путает: пар имён, различающихся только
    этими буквами, не существует.
    """
    return s.replace("ё", "е").replace("й", "и")


_yo = _fold          # прежнее имя оставлено, чтобы не ломать вызовы


# Суффикс после подчёркивания — пометка для читателя, а не часть имени.
# Запись выбрасывается только если пометка противоречит блоку.
_MARK_F, _MARK_M, _MARK_A = "ж", "м", "а"


def _mk(block, gender):
    """gender: 'f' | 'm' | 'a' — какой блок разбираем."""
    out = set()
    for w in block.split():
        if not w:
            continue
        mark = ""
        if "_" in w:
            head, _, tail = w.rpartition("_")
            # пометка — короткий ярлык из кириллицы: _ж, _м, _а, _г, _сл, _стоп
            if head and _re.fullmatch(r"[а-яё]{1,4}", tail):
                w, mark = head, tail
        if mark == _MARK_A and gender != "a":
            continue                                   # спорное — только в AMBIG
        if gender == "f" and mark == _MARK_M:
            continue                                   # помечено мужским
        if gender == "m" and mark == _MARK_F:
            continue                                   # помечено женским
        out.add(_fold(w))
    return out


F = _mk(F_EXACT, "f") | _mk(F_ADD, "f") | _mk(F_ADD2, "f")
M = _mk(M_EXACT, "m") | _mk(M_ADD, "m") | _mk(M_ADD2, "m")
A = _mk(AMBIG, "a")
# Попавшее в оба списка — спорное по определению: «Кира» носят и те и те.
A |= (F & M)
# имя не может быть одновременно и однозначным, и спорным: спорное сильнее
F -= A
M -= A
STEMS = [(_fold(s), n, g) for s, n, g in (F_STEMS + M_STEMS)]
# длинные основы вперёд — «катерин» должен сработать раньше «кать»
STEMS.sort(key=lambda x: -len(x[0]))


# ---------------------------------------------------------------- фамилии
# Фамилии встречаются в поле ИМЕНИ и в НИКЕ: «Dmitryeva», «Vasilyeva_15D»,
# «zhastalapoff», «abdizhusupovaa». Это сильный и однозначный сигнал.
_SURN_F = _re.compile(r"(ова|ева|ина|ына|ская|цкая)$")
# «ский/цкий» пишем через «и»: вход приходит после _fold, где й→и,
# иначе мужское окончание недостижимо, а женское «-ская» работает,
# и получается односторонний женский перекос.
_SURN_M = _re.compile(r"(ов|ев|ин|ын|скии|цкии|офф|ефф)$")

# Обычные слова с фамильными окончаниями. Раньше список был написан
# основами («мужчин»), а сравнение шло по точному равенству — не срабатывал
# никогда, и «мужчина» уверенно определялся как женщина.
# Теперь от основы разворачивается падежная парадигма.
_STOP_STEMS = """
мужчин женщин картин машин витрин корзин резин ангин общин дружин лавин
рутин вершин паутин скотин долин глин новин основ голов коров
пружин тишин вышин толщин седин причин пучин лучин овчин
"""
# полные формы, которые сами по себе похожи на фамилию
_STOP_WORDS = """
один блин господин магазин бензин камин кувшин витамин карантин
апельсин мандарин кретин кабин
"""
_CASES = ("", "а", "ы", "у", "е", "ой", "ам", "ами", "ах", "ою", "и")


def _expand_stop():
    out = set()
    for stem in _STOP_STEMS.split():
        for c in _CASES:
            out.add(_fold(stem + c))
    for w in _STOP_WORDS.split():
        out.add(_fold(w))
    return out


_SURN_STOP = _expand_stop()


def surname_gender(tok, collapsed=False):
    """
    Пол по морфологии фамилии.
    collapsed=True — токен получен склейкой удвоенных букв. Тогда разрешаем
    только длинные женские окончания: короткое -ев/-ов на склеенном латинском
    нике даёт ложные срабатывания («foxieww» → «фоксиев»).
    """
    t = (tok or "").lower()
    if collapsed:
        # Склеенный токен — слабее обычного, но не бесполезный.
        # Длинные женские окончания разрешаем от 7 букв, мужские от 8:
        # «исмайиловв» → «исмайилов» это настоящая фамилия, а «катиев»
        # из «katieww» — нет. Короткий порог отдавал мужской пол всем
        # английским никам на -eww.
        if len(t) < 7 or not _re.fullmatch(r"[а-яё]+", t) or t in _SURN_STOP:
            return None
        if _re.search(r"(ова|ева|ина|ына|ская|цкая)$", t):
            return "f"
        if len(t) >= 8 and _re.search(r"(ов|ев|ин|ын|скии|цкии)$", t):
            return "m"
        return None
    if len(t) < 6 or t in _SURN_STOP:
        return None
    if not _re.fullmatch(r"[а-яё]+", t):
        return None
    if _SURN_F.search(t):
        return "f"
    if _SURN_M.search(t):
        return "m"
    return None



# Отчество проверяется ПЕРВЫМ: «Антоновна» начинается на основу «антон»,
# и без этой проверки получила бы мужской пол.
_PATR_F = _re.compile(r"(овна|евна|ична|инична)$")
_PATR_M = _re.compile(r"(ович|евич)$")


