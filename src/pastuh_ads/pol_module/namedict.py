NICK_MIN_STEM = 4   # подобрано по замеру: ниже растут случайные совпадения
                    # («xeneto» → «ксенето» → основа «ксен»), выше теряются
                    # верные («sonyaxxwll», «olesiikssss», «its_Alinooo»)


# ------------------------------------------------- три уровня надёжности
# Решения разного качества нельзя смешивать по принципу «первое совпало».
# Уровень 1 — отчество и точный словарь: имя узнано целиком.
# Уровень 2 — морфология фамилии: правило, но однозначное.
# Уровень 3 — основа имени: догадка по началу слова.
LEVEL_EXACT, LEVEL_SURNAME, LEVEL_STEM, LEVEL_ADJ = 1, 2, 3, 4


# Прилагательные и причастия в роде. Женские имена на «-ая» существуют
# (Рая, Зая), и правило даёт им верный ответ, так что пересечения не мешают.
# Мужские «-ии» совпадают с окончанием Василии, Дмитрии, Анатолии — тоже верно.
_ADJ_F = _re.compile(r"(ая|яя)$")
_ADJ_M = _re.compile(r"(ыи|ои|ии|ыйц?|ый|ой|ий)$")
# слова, где это окончание не про род говорящего
_ADJ_STOP = frozenset("""
семья статья история фамилия линия акция партия копия армия магия мафия
энергия россия грузия турция япония полиция комедия трагедия серия
""".split())


def adjective_gender(t):
    if t in _ADJ_STOP:
        return None
    if _ADJ_F.search(t):
        return "f"
    if _ADJ_M.search(t):
        return "m"
    return None


def probe(tok, collapsed=False, min_stem=0):
    """
    Возвращает (уровень, 'f'/'m'/'ambig') или None.
    min_stem — минимальная длина основы; для транслита с латиницы ставим
    NICK_MIN_STEM, иначе «yandex» → «яндекс» садится на короткую основу.
    """
    if not tok:
        return None
    t = _fold(tok.lower())
    if len(t) > 5:
        if _PATR_F.search(t):
            return LEVEL_EXACT, "f"
        if _PATR_M.search(t):
            return LEVEL_EXACT, "m"
    if t in _NAME_STOP:
        return None
    # точный словарь ПЕРЕД морфологией фамилий: «Жасмин» — имя, а не «-ин»
    if t in A:
        return LEVEL_EXACT, "ambig"
    if t in F:
        return LEVEL_EXACT, "f"
    if t in M:
        return LEVEL_EXACT, "m"
    sg = surname_gender(t, collapsed=collapsed)
    if sg:
        return LEVEL_SURNAME, sg
    for stem, minlen, g in STEMS:
        if len(stem) < min_stem:
            continue
        if len(t) >= minlen and t.startswith(stem):
            return LEVEL_STEM, g
    # ОТКЛОНЕНО: род прилагательного. Правило давало +0.9пп покрытия на 240к,
    # но из 2542 решений информативными были около двухсот. Остальное —
    # прилагательные при существительном, а не самоописание: «удалённый»
    # (удалённые аккаунты, 46 раз, все в мужчин), «добрый вечер», «разводной
    # ключ», «переменная», «мёртвый опиат». У таких профилей поле фамилии
    # пустое, поэтому в проверочную выборку они не попадают и замер точности
    # их не видит — цифра держалась бы, а решения были бы мусорными.
    # Код adjective_gender оставлен выше как документация отрицательного
    # результата; он намеренно не вызывается.
    return None


def lookup(tok, _collapsed=False, _min_stem=0):
    """'f' / 'm' / 'ambig' / None для одного нормализованного токена."""
    r = probe(tok, _collapsed, _min_stem)
    return r[1] if r else None


def lookup_nick(tok, _collapsed=False):
    """Для ников порог основы обязателен — транслит шумит."""
    return lookup(tok, _collapsed=_collapsed, _min_stem=NICK_MIN_STEM)


def resolve(tokens, collapsed_set=None, translit_set=None):
    """
    Разбирает все токены полей имени и фамилии и выбирает ответ по уровню,
    а не по порядку. «Савелла Анохина» раньше давала м: основа «савел»
    срабатывала первой и забирала решение у однозначной женской фамилии.

    Если два решения одного уровня противоречат друг другу — ответа нет.
    Мужское имя при женской фамилии это либо накрутка, либо ошибка ввода,
    и уверенно врать здесь хуже, чем промолчать.
    """
    collapsed_set = collapsed_set or set()
    translit_set = translit_set or set()
    best = {}
    saw_ambig = False
    for t in tokens:
        r = probe(t,
                  collapsed=(t in collapsed_set),
                  min_stem=NICK_MIN_STEM if t in translit_set else 0)
        if not r:
            continue
        lvl, g = r
        if g == "ambig":
            saw_ambig = True
            continue
        best.setdefault(lvl, set()).add(g)
    for lvl in (LEVEL_EXACT, LEVEL_SURNAME, LEVEL_STEM):
        got = best.get(lvl)
        if not got:
            continue
        if len(got) == 1:
            return next(iter(got)), lvl
        return "conflict", lvl
    return ("ambig" if saw_ambig else None), None


def lookup_any(tokens, collapsed_set=None, translit_set=None):
    g, _ = resolve(tokens, collapsed_set, translit_set)
    return g


def lookup_any_nick(tokens, collapsed_set=None):
    """Ники: порог основы на всех токенах, решение по уровню."""
    collapsed_set = collapsed_set or set()
    g, _ = resolve(tokens, collapsed_set, translit_set=set(tokens))
    return g




# ---------------------------------------------------------------- слова в нике
# Ищутся как подстроки В ИСХОДНОЙ латинице: ник не режется на части
# («prettyboy586»), а транслит добавляет шум. Только однозначные слова.
# Поиск шёл подстрокой по всему нику, и короткие слова ловили что попало:
# «fucking» → king → м, «maniqursaltbomb» → man → м, «missing» → miss → ж.
# Три четверти решений этого правила держались на кусках man / bro / boy.
# Теперь у каждого слова указано, как ему разрешено прилегать к токену:
#   "="  только целым токеном            bro, man, miss, dude
#   "^"  целым или началом токена        king → kingsize, но не fucking
#   "$"  целым или концом токена         boy  → prettyboy, но не boyfriend
#   "*"  целым, началом или концом       girl, queen
#   "~"  где угодно внутри токена        только слова от 5 букв: случайное
#                                        совпадение на такой длине редкость
_NICK_WORDS = (
    ("girl",      "f", "*"), ("lady",      "f", "*"), ("queen",   "f", "~"),
    ("princess",  "f", "~"), ("miss",      "f", "="), ("babe",    "f", "*"),
    ("mommy",     "f", "~"), ("sister",    "f", "~"), ("madam",   "f", "~"),
    ("krasotka",  "f", "~"), ("devochka",  "f", "~"), ("devushka", "f", "~"),
    ("malyshka",  "f", "~"), ("kiska",     "f", "="), ("zaika",   "f", "="),
    ("dochka",    "f", "$"), ("mamochka",  "f", "~"), ("krasavica", "f", "~"),
    ("babes",     "f", "~"), ("girly",     "f", "~"), ("musulmanka", "f", "~"),

    ("boy",       "m", "$"), ("king",      "m", "^"), ("mister",  "m", "~"),
    ("prince",    "m", "^"), ("dude",      "m", "="), ("bro",     "m", "="),
    ("man",       "m", "$"), ("daddy",     "m", "~"), ("brother", "m", "~"),
    ("pacan",     "m", "~"), ("malchik",   "m", "~"), ("muzhik",  "m", "~"),
    ("bratan",    "m", "~"), ("chuvak",    "m", "~"), ("batya",   "m", "="),
)
# Слова, внутри которых гендерный кусок — совпадение, а не смысл.
# Проверяются на целом токене до разбора.
_NICK_STOP = frozenset("""
woman boyko manual roman german normal human command demand manga manager
romantic mango diamond lemon salman osman usman arman iman boyfriend
girlfriend mangal bromance bronx bronze broken broke brother_stop brodyaga
missing mission missile mississippi kingdom kingston shaman ataman
dekan kanban banan talisman alleman
""".split())


def _hit(tok, word, mode):
    if tok == word:
        return True
    if len(tok) <= len(word):
        return False
    if mode == "=":
        return False
    if mode == "~":
        return word in tok
    if mode in ("^", "*") and tok.startswith(word):
        return True
    if mode in ("$", "*") and tok.endswith(word):
        return True
    return False


def _nick_pieces(username):
    """Ник на токены: по разделителям, цифрам и смене регистра."""
    u = username or ""
    u = _re.sub(r"\d+", " ", u)
    u = _re.sub(r"(?<=[a-zа-яё])(?=[A-ZА-ЯЁ])", " ", u)
    return [p.lower() for p in _re.split(r"[\s._\-]+", u) if p]


def nick_word(username):
    """Гендерное слово внутри ника. None, если его нет или оно спорное."""
    if not isinstance(username, str):
        return None
    u = username.lower()
    if len(u) < 4:
        return None
    toks = _nick_pieces(username)
    f = m = False
    for tok in toks:
        if tok in _NICK_STOP:
            continue
        for word, g, mode in _NICK_WORDS:
            if _hit(tok, word, mode):
                if g == "f":
                    f = True
                else:
                    m = True
    if f and not m:
        return "f"
    if m and not f:
        return "m"
    return None
